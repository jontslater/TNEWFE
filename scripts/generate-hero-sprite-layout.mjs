#!/usr/bin/env node
/** Measures idle frame 0 alpha bbox per hero role → heroSpriteLayout.generated.ts */
import fs from 'fs';
import path from 'path';
import sharp from 'sharp';
import { fileURLToPath } from 'url';

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'src/utils/heroSpriteLayout.generated.ts');

async function alphaBounds(pngPath) {
  const { data, info } = await sharp(pngPath)
    .ensureAlpha()
    .raw()
    .toBuffer({ resolveWithObject: true });
  let top = info.height;
  let bottom = -1;
  for (let y = 0; y < info.height; y++) {
    for (let x = 0; x < info.width; x++) {
      const a = data[(y * info.width + x) * info.channels + 3];
      if (a > 32) {
        if (y < top) top = y;
        if (y > bottom) bottom = y;
      }
    }
  }
  if (bottom < 0) {
    return { contentTop: 0, contentBottom: info.height - 1, frameHeight: info.height };
  }
  return { contentTop: top, contentBottom: bottom, frameHeight: info.height };
}

function parseHeroEntries() {
  const heroConfig = fs.readFileSync(
    path.join(ROOT, 'src/utils/spriteConfig.ts'),
    'utf8'
  );
  const luiz = fs.readFileSync(
    path.join(ROOT, 'src/utils/luizmeloHeroSpriteConfig.ts'),
    'utf8'
  );
  const entries = [];
  const roleStarts = [...heroConfig.matchAll(/\n  ([\w-]+): \{/g)];
  for (let i = 0; i < roleStarts.length; i++) {
    const role = roleStarts[i][1];
    const start = roleStarts[i].index;
    const end = i + 1 < roleStarts.length ? roleStarts[i + 1].index : heroConfig.length;
    const block = heroConfig.slice(start, end);
    if (!block.includes('isAnimated: true')) continue;
    const idle = block.match(/idle:\s*'(\/Sprites\/[^']+)'/);
    const fc = block.match(/frameCount:\s*\{[^}]*idle:\s*(\d+)/s);
    if (idle && fc) {
      entries.push({
        id: role,
        sheet: idle[1],
        frameCount: Number(fc[1]),
      });
    }
  }
  for (const role of [...luiz.matchAll(/^\s{2}([\w-]+):\s*luizHero/gm)].map((x) => x[1])) {
    const blockMatch = luiz.match(
      new RegExp(`\\n  ${role}:\\s*luizHero\\([\\s\\S]*?\\),`, 'm')
    );
    if (!blockMatch) continue;
    const packDir = blockMatch[0].match(/luizHero\(\s*'([^']+)'/)?.[1];
    const variant = blockMatch[0].match(/,\s*'([^']+)'/)?.[1] ?? 'base';
    if (!packDir) continue;
    const sheet = `/Sprites/Heroes/HeroSprites/LuizMelo/${packDir}/variants/${variant}/Idle.png`;
    let frameCount = 6;
    if (packDir === 'Hero Knight') frameCount = 11;
    else if (packDir === 'Medieval Warrior') frameCount = 6;
    else if (packDir === 'Martial Hero') frameCount = 8;
    else if (packDir === 'Huntress') frameCount = 8;
    else if (packDir === 'Wizard') frameCount = 6;
    entries.push({ id: role, sheet, frameCount });
  }
  const byId = new Map();
  for (const e of entries) byId.set(e.id, e);
  return [...byId.values()];
}

async function measureEntry(entry) {
  const filePath = path.join(ROOT, 'public', entry.sheet.replace(/^\//, ''));
  if (!fs.existsSync(filePath)) {
    return { id: entry.id, error: 'missing' };
  }
  const meta = await sharp(filePath).metadata();
  const fw = Math.floor(meta.width / entry.frameCount);
  const framePath = path.join(ROOT, 'tmp-hero-layout-frame.png');
  await sharp(filePath)
    .extract({ left: 0, top: 0, width: fw, height: meta.height })
    .png()
    .toFile(framePath);
  const bounds = await alphaBounds(framePath);
  fs.unlinkSync(framePath);
  return {
    id: entry.id,
    contentTop: bounds.contentTop,
    contentBottom: bounds.contentBottom,
    frameHeight: bounds.frameHeight,
  };
}

const entries = parseHeroEntries();
const layout = {};
for (const entry of entries) {
  const m = await measureEntry(entry);
  if (m.error) {
    console.warn('skip', m.id, m.error);
    continue;
  }
  layout[m.id] = {
    contentTop: m.contentTop,
    contentBottom: m.contentBottom,
  };
}

const body = `/** Auto-generated by scripts/generate-hero-sprite-layout.mjs — do not edit */
export type HeroIdleLayout = { contentTop: number; contentBottom: number };

export const HERO_IDLE_LAYOUT: Record<string, HeroIdleLayout> = ${JSON.stringify(layout, null, 2)};
`;

fs.writeFileSync(OUT, body);
console.log(`Wrote ${OUT} (${Object.keys(layout).length} roles)`);
